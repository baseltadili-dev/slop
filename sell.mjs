import fs from "node:fs";
import { JsonRpcProvider, Wallet, Contract, formatUnits } from "ethers";
const RPC="https://mainnet.base.org";
const T="0xA5a3A7a1dec1a57E41A0Cdd8c2129CfD7B46b592";
const W="0x4200000000000000000000000000000000000006";
const ROUTER="0x4752ba5dbc23f44d87826276bf6fd6b1c372ad24";
let pk=(process.env.PK||"").trim();
if(!pk) pk=fs.readFileSync(process.env.HOME+"/.pk","utf8").trim();
const p=new JsonRpcProvider(RPC,8453,{staticNetwork:true});
const w=new Wallet(pk,p), ME=w.address;
const tok=new Contract(T,["function balanceOf(address) view returns (uint256)","function approve(address,uint256) returns (bool)"],w);
const rt=new Contract(ROUTER,["function swapExactTokensForETHSupportingFeeOnTransferTokens(uint256,uint256,address[],address,uint256)"],w);
const g=BigInt((await fetch(RPC,{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"eth_gasPrice",params:[]})}).then(r=>r.json())).result);
const o={maxFeePerGas:g*2n,maxPriorityFeePerGas:10000000n};
const b=await tok.balanceOf(ME);
console.log("تبيع:",formatUnits(b,9),"SLOP");
await (await tok.approve(ROUTER,b,{...o,gasLimit:80000n})).wait();
const t=await rt.swapExactTokensForETHSupportingFeeOnTransferTokens(b,0n,[T,W],ME,Math.floor(Date.now()/1000)+600,{...o,gasLimit:400000n});
const r=await t.wait();
console.log(r.status===1?"تم البيع":"ارتد");
